const DEFAULT_PROVINCE = 'ลพบุรี';

/** RegionService — ไม่ hard-code จังหวัด ใช้คืนค่า climate profile สำหรับอนาคต */
const RegionService = {
  regionOf(name) { return (PROVINCES.find(p => p.name === name) || {}).region || 'C'; },
  climateProfile(name) {
    const r = this.regionOf(name);
    const map = {
      C: 'ร้อนชื้น ช่วงบ่ายร้อนจัด', N: 'ร้อนกลางวัน เย็นช่วงหน้าหนาว', NE: 'ร้อนและแล้งช่วงหน้าร้อน',
      E: 'ร้อนชื้น ฝนชุก', W: 'ร้อน แห้งบางช่วง', S: 'ฝนชุก ความชื้นสูง',
    };
    return { region: r, summary: map[r] };
  },
};
